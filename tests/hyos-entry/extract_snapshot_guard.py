def symbols(elf,section):
 tab=elf.named[section]; strings=elf.section(elf.sections[tab[6]])
 return {elf.cstr(strings,n):(value,size,info&15) for n,info,_,sh,value,size in
         struct.iter_unpack('<IBBHQQ',elf.section(tab)) if n and sh}

def build(images):
 flutter,dart,linker=(images[x] for x in ('flutter','dart','linker'))
 ds=symbols(dart,'.dynsym')
 for name,va,size in SNAPSHOTS:
  assert ds[name][:2] == (va,size)
  assert name[1:] not in ds, 'Given Dart ELF must use underscored fallback symbols'
 ls=symbols(linker,'.symtab')
 for name,va,size in [('__dl_g_dl_mutex',0x1bcb90,40),
                      ('__dl_pthread_mutex_lock',0x5685c,0x128),
                      ('__dl_pthread_mutex_unlock',0x55b6c,0x154),
                      ('__dl__ZN5NonPIL20MutexLockWithTimeoutEP24pthread_mutex_internal_tbPK8timespec',0xe5e28,0x31c)]:
  assert ls[name][:2] == (va,size), (name,ls.get(name))
 assert linker.symbol('__loader_dlsym') == (0x8e1ac,16)
 assert linker.read(0x1bcb90,40) == b'\x00\x40'+bytes(38)
 assert flutter.read(0xfd10e,2) == b'_\0'
 for va,name in [(0xfbce9,'kDartVmSnapshotData'),(0xd59ef,'kDartVmSnapshotInstructions'),
                 (0xfbcfd,'kDartIsolateSnapshotData'),(0xd5a0c,'kDartIsolateSnapshotInstructions')]:
  assert flutter.read(va,len(name)+1) == name.encode()+b'\0'
 calls=[('flutter',0xe89c48,0x10b03a0),('flutter',0xe89cc0,0x6bfd58),
        ('flutter',0x6bfdac,0x10afaf0),('flutter',0x6bffd8,0x10afaf0),
        ('linker',0x7dd14,0x5685c),('linker',0x7dd50,0x55b6c),
        ('linker',0x7e944,0x5685c),('linker',0x7e978,0x55b6c)]
 for image,pc,target in calls:
  assert branch_target(pc,struct.unpack('<I',images[image].read(pc,4))[0])==target,(image,hex(pc))
 assert flutter.read(0x6bffe0,4) == struct.pack('<I',0xf9000a60), 'snapshot x0 store moved'
 text='''// SPDX-License-Identifier: AGPL-3.0-or-later
// Generated by tests/hyos-entry/extract_snapshot_guard.py. Exact supplied
// popsicle OS4.0.0.44 / Home 801027719 identities and complete relevant bodies.
// Private linker layout is valid ONLY after these exact guards. No generic ABI.
#pragma once
#include <array>
#include <cstdint>
namespace hyos_snapshot_guard {
inline constexpr uintptr_t kSearchDlopenReturnVa = 0xe89c4c;
inline constexpr uintptr_t kSnapshotDlsymReturnVa = 0x6bffdc;
inline constexpr uintptr_t kFirstDlsymReturnVa = 0x6bfdb0;
inline constexpr uintptr_t kLoaderDlsymVa = 0x8e1ac;
inline constexpr uintptr_t kMutexVa = 0x1bcb90;
inline constexpr uintptr_t kVmDataVa = 0x340;
inline constexpr std::array<const char *, 4> kSnapshotNames = {
    "_kDartVmSnapshotData", "_kDartVmSnapshotInstructions",
    "_kDartIsolateSnapshotData", "_kDartIsolateSnapshotInstructions"};
'''
 records=[]
 for name,image,va,size,execute in RANGES:
  raw=images[image].read(va,size,execute)
  text+=f'inline constexpr uintptr_t k{name}Va = 0x{va:x};\n'
  text+=array('k'+name,raw,not execute)+'\n'
  records.append(dict(name=name,image=image,va=va,size=size,sha256=hashlib.sha256(raw).hexdigest(),bytes=raw.hex()))
 text+='} // namespace hyos_snapshot_guard\n'
 return text,records,calls

def main():
 p=argparse.ArgumentParser(description=__doc__)
 for name in EXPECTED:p.add_argument('--'+name,required=True,type=Path)
 p.add_argument('--output',required=True,type=Path)
 p.add_argument('--write-header',action='store_true')
 a=p.parse_args(); images={n:Elf(getattr(a,n),sha) for n,sha in EXPECTED.items()}
 text,records,calls=build(images)
 if a.write_header:HEADER.write_text(text)
 elif HEADER.read_text()!=text:raise ValueError('Production guard differs from exact extraction')
 a.output.mkdir(parents=True,exist_ok=False)
 for r in records:(a.output/(r['name']+'.bin')).write_bytes(bytes.fromhex(r['bytes']))
 report={'status':'PASS','header':str(HEADER),'header_sha256':hashlib.sha256(text.encode()).hexdigest(),
  'extractor_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
  'images':{n:{'path':str(e.path),'sha256':e.sha,'pt_load':[dict(va=x[3],filesz=x[5],memsz=x[6],flags=x[1]) for x in e.phdrs if x[0]==1]} for n,e in images.items()},
  'ranges':records,'snapshots':[dict(name=n,va=v,size=s) for n,v,s in SNAPSHOTS],
  'decoded_calls':[dict(image=i,pc=p,target=t) for i,p,t in calls],
  'window':{'dlopen_return':0xe89c4c,'first_dlsym_return':0x6bfdb0,'fallback_dlsym_return':0x6bffdc,'first_snapshot_store':0x6bffe0,
   'first_eligible_snapshot':'_kDartVmSnapshotData','handle_lifetime':'SymbolMapping owns NativeLibrary shared_ptr before dlsym'},
  'mutex':{'va':0x1bcb90,'size':40,'state_offset':0,'state_size':2,'reserved_offset':2,'owner_offset':4,'owner_size':4,'accepted_first_eight_bytes':'0040000000000000',
   'recursive_owner_survives_inner_unlock':True,'gate':'two identical bounded reads, exactly private recursive unlocked state and owner zero; no acquisition'},
  'limitations':['Static supplied-ROM call order, not device injection or UI behavior',
   'Exact methods and ELF metadata checked live, not a runtime hash of every image byte',
   'Other callback/file snapshot paths or already-initialized VM remain unsupported',
   'An unlocked observation is not a reservation against another thread; the executor must not use loader APIs or shared worker locks',
   'process_vm_readv denial/partial read closes window; no proc filesystem fallback or retry']}
 (a.output/'report.json').write_text(json.dumps(report,indent=2)+'\n')
 print('PASS exact snapshot guard extraction:',a.output/'report.json')
if __name__=='__main__':main()
