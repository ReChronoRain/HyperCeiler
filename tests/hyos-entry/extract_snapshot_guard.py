"""Reproduce exact first-snapshot guards for the supplied OS4.0.0.44 ROM.

Reads ELFs, never loads them. Full input hashes are provenance checks; the live
observer uses exact mapped headers, identities and complete relevant methods.
--output must be new. --write-header is an explicit developer operation.
"""
