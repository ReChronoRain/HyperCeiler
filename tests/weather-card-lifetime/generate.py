#!/usr/bin/env python3
"""Emit exact pinned engine/libc guards for the early two-page lifetime observer."""
import argparse,hashlib,importlib.util,json,struct,sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import hyperceiler_test_paths as test_paths

sys.dont_write_bytecode=True
SOURCE=Path(__file__).resolve().parents[2]
ROOT=test_paths.TEST_DATA_ROOT
OUT=SOURCE/'app/src/main/cpp/targets/weather/weather_card_lifetime_guard.generated.h'
SHA=lambda b:hashlib.sha256(b).hexdigest()

def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');p.add_argument('--manifest',type=Path);a=p.parse_args()
 helper=test_paths.TEST_DATA_ROOT / 'acceptance/weather-card-next/guard-v4/extract.py';spec=importlib.util.spec_from_file_location('frozen',helper);g=importlib.util.module_from_spec(spec);spec.loader.exec_module(g)
 paths={'Flutter':test_paths.ROM_ROOT / 'components/system_ext/lib64/libhyper_os_flutter.so','Libc':test_paths.TEST_DATA_ROOT / 'acceptance/weather-card-next/page-lifetime-next/libc.so'}
 shas={'Flutter':g.FLUTTER_SHA,'Libc':'b963b539545b64aa8fbcaed3228d04bcb6466bfd47055aa16e4ccdcadfdc461e'}
 elfs={k:g.Elf(v.read_bytes(),shas[k]) for k,v in paths.items()}
 fs=[(0,832),(0x10aedb0,84),(0xea430c,96),(0x10aee04,168),(0x10aeeac,2076),(0x10af6c8,292),(0x10b05e0,16)]
 # Pin the unique named import through its immutable relocation/symbol/name data.
 e=elfs['Flutter'];sec=e.named['.rela.plt'];sy=e.named['.dynsym'];strings=e.section(e.sections[sy[6]])
 found=[]
 for off,info,add in struct.iter_unpack('<QQq',e.section(sec)):
  idx=info>>32;at=idx*24;n,_,_,sh,va,size=struct.unpack_from('<IBBHQQ',e.section(sy),at)
  if n and e.cstr(strings,n)=='madvise':found.append((off,info&0xffffffff,add,idx,n))
 assert len(found)==1 and found[0][:3]==(0x11143b8,1026,0)
 off,kind,add,idx,n=found[0]
 fs += [(sec[3]+next(i for i,x in enumerate(struct.iter_unpack('<QQq',e.section(sec))) if x[0]==off)*24,24),(sy[3]+idx*24,24),(e.sections[sy[6]][3]+n,8)]
 libc=elfs['Libc'];assert libc.symbol('madvise')==(0xe0340,24)
 prefix=max(64+len(libc.phdrs)*56,max(s[3]+s[5] for name,s in libc.named.items() if name=='.note.gnu.build-id'))
 ls=[(0,prefix),(0xe0340,24),(0x7bcb4,28)]
 lines=['/* SPDX-License-Identifier: AGPL-3.0-or-later */','// Generated by tests/weather-card-lifetime/generate.py; exact supplied ROM only.','#pragma once','#include <array>','#include <cstddef>','#include <cstdint>','namespace weather_card_lifetime_guard {','struct Guard { uintptr_t va; const uint8_t *data; size_t size; };',
 'inline constexpr uintptr_t kMadviseSlotVa=0x11143b8;', 'inline constexpr uintptr_t kMadviseVa=0xe0340;', 'inline constexpr uint32_t kOriginalWord=0xaa1603e0;', 'inline constexpr std::array<uintptr_t,2> kSites={0x3a8408,0x3aece0};']
 records=[]
 for image,ranges in [('Flutter',fs),('Libc',ls)]:
  for i,(va,size) in enumerate(ranges):
   raw=elfs[image].read(va,size);name=f'k{image}Bytes{i}'
   lines.append(f'inline constexpr std::array<uint8_t,{size}> {name}={{')
   for j in range(0,size,16):lines.append(' '+','.join(f'0x{x:02x}' for x in raw[j:j+16])+',')
   lines.append('};');records.append(dict(image=image,va=hex(va),size=size,sha256=SHA(raw)))
  lines.append(f'inline constexpr std::array<Guard,{len(ranges)}> k{image}Guards={{{{')
  lines.extend(f' {{0x{va:x},k{image}Bytes{i}.data(),k{image}Bytes{i}.size()}},' for i,(va,size) in enumerate(ranges));lines.append('}};')
 lines.append('}');text='\n'.join(lines)+'\n'
 if a.check:assert OUT.read_text()==text
 else:OUT.write_text(text)
 if a.manifest:
  assert not a.manifest.exists();a.manifest.parent.mkdir(parents=True,exist_ok=True);a.manifest.write_text(json.dumps(dict(passed=True,header_sha256=SHA(text.encode()),inputs={str(test_paths.report_path(v, ROOT)):shas[k] for k,v in paths.items()},helper_sha256=SHA(helper.read_bytes()),script_sha256=SHA(Path(__file__).read_bytes()),guards=records),indent=2)+'\n')
 print(SHA(text.encode()))

if __name__=='__main__':main()
