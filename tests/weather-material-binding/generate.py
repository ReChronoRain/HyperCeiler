#!/usr/bin/env python3
"""Generate independent material capability guards from four pinned ROM ELFs."""
from pathlib import Path
import argparse,hashlib,importlib.util,json,struct

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import hyperceiler_test_paths as test_paths

ROOT=test_paths.TEST_DATA_ROOT
HEADER=test_paths.SOURCE_ROOT / 'app/src/main/cpp/targets/weather/weather_material_guard.generated.h'
OLD=test_paths.SOURCE_ROOT / 'tests/weather-binding/generate.py'
spec=importlib.util.spec_from_file_location('weather_elf_reader',OLD);reader=importlib.util.module_from_spec(spec);spec.loader.exec_module(reader)
sha=lambda b:hashlib.sha256(b).hexdigest()
def generate():
 evidence=test_paths.TEST_DATA_ROOT / 'acceptance/weather-blur-next/evidence-v4/guard-inputs.json';report=json.loads(evidence.read_text())
 paths={'Weather':test_paths.TEST_DATA_ROOT / 'acceptance/native-evidence/weather-libweather_app.so','Public':test_paths.EXTRACTED_ROM_ROOT / 'system_ext/lib64/libhyper_os_system_public.so','Private':test_paths.EXTRACTED_ROM_ROOT / 'system_ext/lib64/libhyper_os_core_system_private.dylib.so','Dart':test_paths.TEST_DATA_ROOT / 'acceptance/native-evidence/weather-libapp.so'}
 els={n:reader.Elf(p,report['inputs'][str(p)])for n,p in paths.items()}
 regions={n:[]for n in els}
 def add(image,name,va,size,expected=None):
  e=els[image];data=e.read(va,size)
  assert expected is None or sha(data)==expected,(image,name)
  assert not any(va<=x['slot']<va+size for x in e.relocations()),(image,name,'relocated exact span')
  regions[image].append(dict(name=name,va=va,size=size,sha256=sha(data),bytes=data))
 for name,e in els.items():
  add(name,'elf-header-and-program-headers',0,e.phend)
  for i,p in enumerate(x for x in e.ph if x[0]==4):add(name,'elf-note-'+str(i),p[3],p[5])
 for name,r in report['native_functions'].items():
  image=next(n for n,p in paths.items()if str(p)==r['elf'])
  add(image,name,int(r['va'],0),r['size'],r['sha256'])
 for r in report['data']:
  if r['va']=='0x6c1548':continue # Mutable Lazy state is a separate startup-time read.
  add('Weather','literal-'+r['va'],int(r['va'],0),r['size'],r['sha256'])
 for name,r in report['dart_functions'].items():add('Dart',name,int(r['va'],0),r['size'],r['sha256'])
 # Snapshot headers bind the format/version too, without guarding mutable heap data.
 for name,va in [('vm-snapshot-header',0x340),('isolate-snapshot-header',0x4ac0)]:
  data=els['Dart'].read(va,256);end=data.index(0,52)+1;add('Dart',name,va,end)
 private_name=report['public_import']['symbol']
 for image,symbol,va,size in [('Public','SystemProperties_get_bool',0x129b8,24),('Private',private_name,0x34b14,220)]:
  assert any(n==symbol and v==va and z==size and ix!=0 for n,v,z,_,ix in els[image].symbols)
 for image,slot,symbol in [('Weather',0x6badc8,'SystemProperties_get_bool'),('Public',0x18a48,private_name)]:
  assert any(r['slot']==slot and r['type']==1026 and r['symbol']==symbol for r in els[image].relocations())
 vtables=[(int(k,0),int(v,0))for k,v in report['vtable_relocations'].items()]
 for slot,target in vtables:assert any(r['slot']==slot and r['type']==1027 and r['addend']==target for r in els['Weather'].relocations())
 exports={}
 for name in ['_kDartVmSnapshotData','_kDartVmSnapshotInstructions','_kDartIsolateSnapshotData','_kDartIsolateSnapshotInstructions']:
  symbol=[x for x in els['Dart'].symbols if x[0]==name and x[4]!=0];assert len(symbol)==1;exports[name]=symbol[0][1]
 constants={'kWeatherPropertySlot':0x6badc8,'kPublicGetVa':0x129b8,'kPublicPrivateSlot':0x18a48,'kPrivateGetVa':0x34b14,'kLazyStateVa':0x6c1548,'kDartVmDataVa':exports['_kDartVmSnapshotData'],'kDartVmInstructionsVa':exports['_kDartVmSnapshotInstructions'],'kDartIsolateDataVa':exports['_kDartIsolateSnapshotData'],'kDartIsolateInstructionsVa':exports['_kDartIsolateSnapshotInstructions']}
 text=['/* SPDX-License-Identifier: AGPL-3.0-or-later */','// Generated by tests/weather-material-binding/generate.py; do not hand edit.','#pragma once','#include <array>','#include <cstddef>','#include <cstdint>','#include <span>','namespace weather_material_guard {','struct Guard {uintptr_t va; std::span<const uint8_t> bytes;};','struct Import {uintptr_t slot,target;};']
 for n,v in constants.items():text.append(f'inline constexpr uintptr_t {n}=0x{v:x};')
 for image,e in els.items():
  text.append(f'inline constexpr uintptr_t k{image}ImageSpan=0x{e.span:x};')
  text.append(f'inline constexpr char k{image}SourceSha256[]="{sha(e.data)}";')
  for i,r in enumerate(regions[image]):
   text.append(f'// {r["name"]}; RVA0x{r["va"]:x}; {r["size"]} bytes; SHA256 {r["sha256"]}')
   text.append(f'inline constexpr std::array<uint8_t,{r["size"]}> k{image}Bytes{i}={{')
   for j in range(0,r['size'],16):text.append('    '+','.join(f'0x{x:02x}'for x in r['bytes'][j:j+16])+',')
   text.append('};')
  text.append(f'inline constexpr std::array<Guard,{len(regions[image])}> k{image}Guards={{{{')
  for i,r in enumerate(regions[image]):text.append(f'    {{0x{r["va"]:x},k{image}Bytes{i}}},')
  text.append('}};')
 text.append(f'inline constexpr std::array<Import,{len(vtables)}> kWeatherVtables={{{{')
 text +=[f'    {{0x{s:x},0x{t:x}}},'for s,t in vtables];text+=['}};','} // namespace weather_material_guard','']
 manifest={'inputs':{n:{'path':str(e.path),'sha256':sha(e.data),'image_span':e.span,'loads':[dict(va=p[3],file_offset=p[2],filesz=p[5],memsz=p[6],flags=p[1])for p in e.ph if p[0]==1]}for n,e in els.items()},'evidence_inputs':{str(evidence):sha(evidence.read_bytes()),str(OLD):sha(OLD.read_bytes())},'guards':{n:[{k:v for k,v in r.items()if k!='bytes'}for r in rows]for n,rows in regions.items()},'constants':constants,'weather_vtables':vtables,'weather_imports':[[0x6badc8,0x129b8]],'private_imports':[[0x18a48,0x34b14]],'exports':exports,'scope':'Independent material binding, no DeviceLevel allocator dependency; readonly Lazy cold-state3 check is separate and not a reservation.'}
 return '\n'.join(text),manifest
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--output',required=True,type=Path);p.add_argument('--header',type=Path,default=HEADER);p.add_argument('--check',action='store_true');a=p.parse_args();text,m=generate();again,_=generate();assert text==again
 a.output.mkdir(parents=True,exist_ok=False)
 if a.check:assert a.header.read_text()==text,'generated header drift'
 else:a.header.write_text(text)
 m.update(passed=True,regeneration_identical=True,mode='check'if a.check else'generate',header={'path':str(a.header),'sha256':sha(a.header.read_bytes())},generator={'path':str(Path(__file__).resolve()),'sha256':sha(Path(__file__).read_bytes())})
 (a.output/'guard-manifest.json').write_text(json.dumps(m,indent=2)+'\n');print(json.dumps({'passed':True,'guards':{k:len(v)for k,v in m['guards'].items()},'bytes':sum(x['size']for rows in m['guards'].values()for x in rows),'header':m['header']}))
if __name__=='__main__':main()
