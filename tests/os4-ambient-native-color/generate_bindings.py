#!/usr/bin/env python3
"""Reproduce the exact OTA's self-owned algorithm relocations, never vendor bytes."""
from pathlib import Path
import argparse, hashlib, importlib.util, json, struct, sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import hyperceiler_test_paths as test_paths

sys.dont_write_bytecode=True
ROOT=Path(__file__).resolve().parents[2]
FILE_SHA='652eb3fb8850b46a4df0865c1abf4f3ca5b0084d828dceb5ce547be86e1d1852'
p=argparse.ArgumentParser();p.add_argument('--library',type=Path,default=test_paths.EXTRACTED_ROM_ROOT / 'system_ext/lib64/libMiMainColor.so');p.add_argument('--check',action='store_true');p.add_argument('--report',type=Path);a=p.parse_args()
s=importlib.util.spec_from_file_location('elf_reader',test_paths.TEST_DATA_ROOT / 'tools/verify-test4-deliverables.py');m=importlib.util.module_from_spec(s);s.loader.exec_module(m)
b=a.library.read_bytes();assert hashlib.sha256(b).hexdigest()==FILE_SHA;e=m.Elf(b);rows=[]
for sec in e.sections:
 if sec[1]!=4:continue
 symbols=e.sections[sec[6]];strings=e.content(e.sections[symbols[6]])
 for pos in range(sec[4],sec[4]+sec[5],sec[9]):
  va,info,addend=struct.unpack_from('<QQq',b,pos);n,kind,other,index,target,size=struct.unpack_from('<IBBHQQ',b,symbols[4]+24*(info>>32));name=e.string(strings,n)
  if index and (name=='process' or any(x in name for x in ('MainColor','material_color_utilities','ThreadPool'))):
   assert info&0xffffffff in (257,1025,1026) and addend==0
   rows.append(dict(slot=va,target=target,name=name,type=info&0xffffffff))
rows.sort(key=lambda x:x['slot']);assert len(rows)==105 and len({x['slot']for x in rows})==105
head='''/* SPDX-License-Identifier: AGPL-3.0-or-later */
// Generated by tests/os4-ambient-native-color/generate_bindings.py.
// Exact SHA256: '''+FILE_SHA+'''
// All dynamic relocations to this DSO's MainColor/material/ThreadPool domain,
// including specialized STL helpers; generic libc/libc++ APIs are not included.
#pragma once
#include <array>
#include <cstdint>
namespace ambient_os4 {
struct SelfBinding { uintptr_t slot; uintptr_t target; const char* name; };
inline constexpr std::array<SelfBinding,105> kSelfBindings{{
'''
head+=''.join('    {0x%x,0x%x,"%s"},\n'%(x['slot'],x['target'],x['name'])for x in rows)+'}};\n} // namespace ambient_os4\n'
path=ROOT/'app/src/main/cpp/targets/systemui/ambient_bindings.generated.h'
if a.check:assert path.read_text()==head
else:path.write_text(head)
if a.report:
 a.report.parent.mkdir(parents=True,exist_ok=True);a.report.write_text(json.dumps(dict(passed=True,library_sha256=FILE_SHA,header_sha256=hashlib.sha256(head.encode()).hexdigest(),bindings=rows,count=len(rows),device_status='NOT_TESTED'),indent=2)+'\n')
print('105 exact self-domain relocations verified')
